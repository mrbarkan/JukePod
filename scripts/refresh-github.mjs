// Refreshes GitHub star counts for every firmware that has a `github` field,
// and writes them to data/github-stats.js, which the page reads on load.
//
//   node scripts/refresh-github.mjs
//
// Set GITHUB_TOKEN to avoid the 60-requests-per-hour anonymous limit.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const root = new URL("..", import.meta.url);
const dataPath = fileURLToPath(new URL("data/firmwares.js", root));
const outPath = fileURLToPath(new URL("data/github-stats.js", root));

const sandbox = { window: {} };
vm.runInNewContext(readFileSync(dataPath, "utf8"), sandbox);
const { firmwares } = sandbox.window.IPOD_FIRMWARE_DATA;

const headers = { "User-Agent": "firmware-catalog", Accept: "application/vnd.github+json" };
if (process.env.GITHUB_TOKEN) headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;

const stats = {};
for (const fw of firmwares) {
  if (!fw.github) continue;
  const res = await fetch(`https://api.github.com/repos/${fw.github}`, { headers });
  if (!res.ok) {
    console.warn(`${fw.id}: GitHub answered ${res.status}, keeping the old count`);
    continue;
  }
  const repo = await res.json();
  stats[fw.id] = { stars: repo.stargazers_count };
  console.log(`${fw.id}: ${repo.stargazers_count} stars`);
}

const today = new Date().toISOString().slice(0, 10);
writeFileSync(
  outPath,
  `// Generated by scripts/refresh-github.mjs on ${today}. Do not edit by hand.\n` +
    `window.IPOD_GITHUB_STATS = ${JSON.stringify({ date: today, repos: stats }, null, 2)};\n`
);
console.log(`Wrote ${outPath}`);
